-- 0005_guilds.sql — 行会（guild / 行会）持久化。
--
-- 对应 Crystal 的三处状态：
--
-- | Crystal | 本迁移 |
-- |---|---|
-- | `GuildInfo`（`Server/MirDatabase/GuildInfo.cs:7-38`，存 `Guilds/<index>.mgd`） | `guilds` 一行 |
-- | `GuildRank` + `GuildRank.Members`（`Shared/Data/GuildData.cs:1`、`:62`） | `guild_ranks` + `guild_members` |
-- | `CharacterInfo.GuildIndex`（`Server/MirDatabase/CharacterInfo.cs`） | 已有的 `characters.guild_index` 列 |
--
-- 与 Crystal 二进制存档的差异：Crystal 把成员**塞在职位里**（`GuildRank.Members`），
-- 本迁移把成员单独成表，靠 `rank_index` 指回职位。这样「一个角色只能在一个行会」
-- 可以直接用主键约束表达，登录时也只查一行。
--
-- `notice` 是公告的每一行，用 `\n` 连接后存一个 TEXT（Crystal 存 `List<string>`）。
-- 行会仓库（`GuildInfo.StoredItems`，112 格）尚未实现，见 `docs/world/guild.md` 的「未做」。

CREATE TABLE guilds (
    -- 行会主键 = Crystal `GuildInfo.GuildIndex`。用 `GENERATED BY DEFAULT AS IDENTITY` 而不是
    -- `SERIAL`：世界层自己分配 ID（`Envir.NextGuildID`，`Envir.cs:126`），落库时要按同一个
    -- 号写进去，`SERIAL` 的默认值不接受显式值。
    id                  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- 行会名：Crystal 用 `GetGuild(name)` 比较时**去掉空格 + 忽略大小写**
    -- （`Server/MirEnvir/Envir.cs:4832-4841`），所以唯一索引建在 `lower(name)` 上。
    name                TEXT NOT NULL,
    -- 会长角色（`GuildInfo` 的 rank 0 成员；这里额外记一列，便于删除角色时对账）。
    leader_character_id BIGINT NOT NULL REFERENCES characters (id) ON DELETE CASCADE,
    -- `GuildInfo.Level`（byte，`GuildInfo.cs:11`）。
    level               SMALLINT NOT NULL DEFAULT 0,
    -- `GuildInfo.Experience`（long，`GuildInfo.cs:13`）。
    experience          BIGINT NOT NULL DEFAULT 0,
    -- `GuildInfo.Gold`（uint，`GuildInfo.cs:14`）。
    gold                BIGINT NOT NULL DEFAULT 0,
    -- `GuildInfo.SparePoints`（byte，`GuildInfo.cs:12`）。
    spare_points        SMALLINT NOT NULL DEFAULT 0,
    -- 公告全文（每行之间用 `\n`）。
    notice              TEXT NOT NULL DEFAULT '',
    created_at          TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX guilds_name_ci_key ON guilds (lower(name));

CREATE TABLE guild_ranks (
    guild_id   INTEGER NOT NULL REFERENCES guilds (id) ON DELETE CASCADE,
    -- 职位序号（Crystal `GuildRank.Index`，0 = 会长）。列名避开 SQL 关键字 `index`。
    rank_index SMALLINT NOT NULL,
    name       TEXT NOT NULL,
    -- Crystal `GuildRankOptions`（`Shared/Enums.cs:1897-1908`）的位掩码：
    -- 1 CanChangeRank / 2 CanRecruit / 4 CanKick / 8 CanStoreItem / 16 CanRetrieveItem /
    -- 32 CanAlterAlliance / 64 CanChangeNotice / 128 CanActivateBuff。会长固定 255。
    options    SMALLINT NOT NULL DEFAULT 0,
    PRIMARY KEY (guild_id, rank_index)
);

CREATE TABLE guild_members (
    -- 主键 = 角色：一个角色只能在一个行会（Crystal 是 `CharacterInfo.GuildIndex` 单值）。
    character_id BIGINT PRIMARY KEY REFERENCES characters (id) ON DELETE CASCADE,
    guild_id     INTEGER NOT NULL REFERENCES guilds (id) ON DELETE CASCADE,
    -- 该成员所属职位（`guild_ranks.rank_index`）。
    rank_index   SMALLINT NOT NULL DEFAULT 1,
    joined_at    TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX guild_members_guild_key ON guild_members (guild_id);
