"""Entry point: regenerate Rust protocol code from a Crystal checkout.

Usage:
    py generate.py [--crystal C:/Users/diana/ref/Crystal] [--check]

`--check` only verifies that the checked-in Rust matches what the generator would
produce, without writing files (used by CI when a Crystal checkout exists).
"""

from __future__ import annotations

import argparse
import os
import subprocess
import sys
import tempfile
from pathlib import Path

from crystal_codegen import Ctx, TranslationError, translate_read, translate_write
from crystal_enums import emit_rust_enums, parse_enum_file
from crystal_packets import PacketDef, iter_units, load_packets
from crystal_types import TypeRegistry, snake_case

REPO_ROOT = Path(__file__).resolve().parents[2]

# C# data classes that already have a hand-written Rust counterpart in
# `mir-protocol`. Packets referring to anything outside this set are deferred
# until the data class is implemented.
IMPLEMENTED_STRUCTS = {
    "UserItem",
    "SelectInfo",
}

PACKET_HEADER = """// Generated by tools/protocol-gen/generate.py from the Crystal C# sources.
// Do not edit by hand: re-run the generator instead.
#![allow(
    clippy::struct_excessive_bools,
    clippy::too_many_lines,
    clippy::similar_names,
    clippy::field_reassign_with_default,
    clippy::wildcard_imports,
    clippy::too_many_arguments,
    unused_imports
)]

use crate::data::*;
use crate::*;
"""

# Packets whose C# body the translator cannot express yet (bit flags, nested
# optionals, or data classes without a Rust counterpart). They are implemented by
# hand in `crates/mir-protocol/src/manual/<direction>.rs` and only re-exported
# here so the packet enum stays complete.
HAND_WRITTEN = {
    "client": {"Chat"},
    "server": {"MapInformation", "UserInformation"},
}


def build_registry(enums: dict) -> TypeRegistry:
    underlying = {name: enum.underlying for name, enum in enums.items()}
    return TypeRegistry(underlying, IMPLEMENTED_STRUCTS, set())


def translate_packet(packet: PacketDef, registry: TypeRegistry) -> tuple[list[str], list[str], str]:
    read_body = packet.read_body or ""
    write_body = packet.write_body or ""
    read_units, _ = iter_units(read_body)
    write_units, _ = iter_units(write_body)
    fields = {f.name: f for f in packet.fields}
    read_translation = translate_read(read_units, Ctx(registry=registry, fields=fields, out="out"))
    write_translation = translate_write(write_units, Ctx(registry=registry, fields=fields, out="self"))
    if read_translation.signature != write_translation.signature:
        raise TranslationError(
            f"read signature {read_translation.signature} != write signature {write_translation.signature}"
        )
    return read_translation.lines, write_translation.lines, " ".join(read_translation.signature)


def emit_packet_struct(packet: PacketDef, registry: TypeRegistry) -> str:
    read_lines, write_lines, _ = translate_packet(packet, registry)
    lines: list[str] = []
    lines.append(f"/// Crystal `{packet.direction.title()}Packets.{packet.name}` (index {packet.index_value}).")
    lines.append("#[derive(Debug, Clone, Default, PartialEq)]")
    lines.append(f"pub struct {packet.name} {{")
    seen: set[str] = set()
    for decl in packet.fields:
        resolved = registry.resolve(decl.cs_type)
        if resolved is None:
            raise TranslationError(f"unsupported field type {decl.cs_type!r} for {decl.name!r}")
        if resolved.kind == "struct":
            rust_type = f"Option<{resolved.rust}>" if _field_is_optional(packet, decl.name) else resolved.rust
        elif resolved.kind == "array" and _array_is_optional(packet, decl.name):
            element = resolved.rust[len("Vec<") : -1]
            rust_type = f"Vec<Option<{element}>>"
        else:
            rust_type = resolved.rust
        field_name = snake_case(decl.name)
        if field_name in seen:
            field_name += "_"
        seen.add(field_name)
        lines.append(f"    pub {field_name}: {rust_type},")
    lines.append("}")
    lines.append("")
    lines.append(f"impl {packet.name} {{")
    lines.append(f"    /// Packet index used on the wire.")
    lines.append(f"    pub const INDEX: i16 = {packet.index_value};")
    lines.append("    /// Whether Crystal gzip-compresses this packet's payload.")
    lines.append(f"    pub const COMPRESSED: bool = {'true' if packet.compressed else 'false'};")
    lines.append("")
    lines.append("    /// Decode the packet payload (without the header).")
    reader_name = "r" if read_lines else "_r"
    lines.append(
        f"    pub fn decode({reader_name}: &mut crate::PacketReader<'_>) -> Result<Self, crate::ProtocolError> {{"
    )
    if read_lines:
        lines.append("        let mut out = Self::default();")
        for line in read_lines:
            lines.extend(_indent(line, 8))
        lines.append("        Ok(out)")
    else:
        lines.append("        Ok(Self::default())")
    lines.append("    }")
    lines.append("")
    lines.append("    /// Encode the packet payload (without the header).")
    writer_name = "w" if write_lines else "_w"
    lines.append(f"    pub fn encode(&self, {writer_name}: &mut crate::PacketWriter) {{")
    for line in write_lines:
        lines.extend(_indent(line, 8))
    lines.append("    }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def _indent(line: str, spaces: int) -> list[str]:
    return [(" " * spaces) + line]


def _field_is_optional(packet: PacketDef, field_name: str) -> bool:
    body = (packet.read_body or "").replace("\n", " ")
    body = " ".join(body.split())
    return (
        f"if (reader.ReadBoolean()) {field_name} = " in body
        or f"if (reader.ReadBoolean()) {field_name}=" in body
    )


def _array_is_optional(packet: PacketDef, field_name: str) -> bool:
    body = (packet.read_body or "").replace("\n", " ")
    body = " ".join(body.split())
    marker = f"{field_name}[i] ="
    if marker not in body:
        return False
    return "reader.ReadBoolean()) continue" in body or "reader.ReadBoolean()) " + marker in body


def emit_packet_module(packets: list[PacketDef], registry: TypeRegistry, direction: str) -> str:
    chunks = [PACKET_HEADER]
    emitted: list[PacketDef] = []
    failures: list[tuple[str, str]] = []
    for packet in packets:
        if packet.name in HAND_WRITTEN[direction]:
            chunks.append(
                f"pub use crate::manual::{direction}::{packet.name};\n"
            )
            emitted.append(packet)
            continue
        try:
            chunks.append(emit_packet_struct(packet, registry))
            emitted.append(packet)
        except TranslationError as error:
            failures.append((packet.name, str(error)))
    chunks.append(emit_packet_enum(emitted, direction))
    return "\n".join(chunks), failures


def emit_packet_enum(packets: list[PacketDef], direction: str) -> str:
    enum_name = "ClientPacket" if direction == "client" else "ServerPacket"
    lines = [f"/// Every {direction}→{'server' if direction == 'client' else 'client'} packet Crystal understands."]
    lines.append("#[derive(Debug, Clone, PartialEq)]")
    lines.append(f"pub enum {enum_name} {{")
    for packet in packets:
        lines.append(f"    {packet.name}({packet.name}),")
    lines.append("}")
    lines.append("")
    lines.append(f"impl {enum_name} {{")
    lines.append("    /// Packet index used on the wire.")
    lines.append("    #[must_use]")
    lines.append("    pub const fn index(&self) -> i16 {")
    lines.append("        match self {")
    for packet in packets:
        lines.append(f"            Self::{packet.name}(_) => {packet.name}::INDEX,")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    /// Whether this packet's payload is gzip-compressed.")
    lines.append("    #[must_use]")
    lines.append("    pub const fn compressed(&self) -> bool {")
    lines.append("        match self {")
    for packet in packets:
        lines.append(f"            Self::{packet.name}(_) => {packet.name}::COMPRESSED,")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    /// Decode a packet payload (header already stripped) using the id from the header.")
    lines.append("    pub fn decode(index: i16, payload: &[u8]) -> Result<Self, crate::ProtocolError> {")
    lines.append("        match index {")
    for packet in packets:
        lines.append(f"            {packet.name}::INDEX => {{")
        lines.append(
            f"                let body = crate::codec::decompress_if({packet.name}::COMPRESSED, payload)?;"
        )
        lines.append("                let mut r = crate::PacketReader::new(&body);")
        lines.append(f"                Ok(Self::{packet.name}({packet.name}::decode(&mut r)?))")
        lines.append("            }")
    lines.append("            other => Err(crate::ProtocolError::UnknownPacket { index: other }),")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    /// Encode the payload (header excluded).")
    lines.append("    pub fn encode(&self, w: &mut crate::PacketWriter) {")
    lines.append("        match self {")
    for packet in packets:
        lines.append(f"            Self::{packet.name}(p) => p.encode(w),")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    /// Encode the full frame (header + optional gzip payload).")
    lines.append("    #[must_use]")
    lines.append("    pub fn encode_frame(&self) -> Vec<u8> {")
    lines.append("        let mut w = crate::PacketWriter::new();")
    lines.append("        self.encode(&mut w);")
    lines.append("        crate::codec::frame(self.index(), self.compressed(), w.into_inner())")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def format_rust(content: str) -> str:
    """Run rustfmt over generated code so `cargo fmt --check` and `--check` agree."""
    handle, path = tempfile.mkstemp(suffix=".rs")
    os.close(handle)
    try:
        Path(path).write_text(content, encoding="utf-8")
        subprocess.run(
            ["rustfmt", "--edition", "2024", path],
            check=True,
            capture_output=True,
            text=True,
        )
        return Path(path).read_text(encoding="utf-8")
    except (OSError, subprocess.CalledProcessError) as error:
        print(f"rustfmt 不可用，跳过格式化：{error}", file=sys.stderr)
        return content
    finally:
        Path(path).unlink(missing_ok=True)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--crystal", default="C:/Users/diana/ref/Crystal")
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    crystal = Path(args.crystal)
    if not crystal.exists():
        print(f"Crystal checkout not found at {crystal}", file=sys.stderr)
        raise SystemExit(2)

    enums: dict = {}
    enum_sources = [crystal / "Shared" / "Enums.cs"] + sorted((crystal / "Shared").rglob("*.cs"))
    for path in enum_sources:
        if not path.exists():
            continue
        for enum in parse_enum_file(path):
            enums.setdefault(enum.name, enum)
    registry = build_registry(enums)
    client_packets, server_packets = load_packets(crystal)

    outputs: dict[Path, str] = {}
    outputs[REPO_ROOT / "crates" / "mir-core" / "src" / "enums" / "generated.rs"] = emit_rust_enums(
        list(enums.values()),
        "// Generated by tools/protocol-gen/generate.py from Crystal `Shared/Enums.cs`.\n// Do not edit by hand: re-run the generator instead.",
    )
    report_lines = ["# 协议生成报告", ""]
    for direction, packets in (("client", client_packets), ("server", server_packets)):
        module, failures = emit_packet_module(packets, registry, direction)
        filename = "client.rs" if direction == "client" else "server.rs"
        outputs[REPO_ROOT / "crates" / "mir-protocol" / "src" / "packets" / filename] = module
        report_lines.append(
            f"## {direction}: {len(packets) - len(failures)}/{len(packets)} 自动生成，{len(failures)} 个待手写"
        )
        report_lines.append("")
        for name, reason in failures:
            report_lines.append(f"- `{name}`: {reason}")
        report_lines.append("")
    outputs[REPO_ROOT / "tools" / "protocol-gen" / "report.md"] = "\n".join(report_lines) + "\n"

    changed = 0
    for path, content in outputs.items():
        if path.suffix != ".rs":
            normalized = content.rstrip() + "\n"
        else:
            normalized = format_rust(content).rstrip() + "\n"
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current.rstrip() + "\n" != normalized:
            changed += 1
            if not args.check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(normalized, encoding="utf-8")
    total_packets = len(client_packets) + len(server_packets)
    print(f"packets: {total_packets}, files changed: {changed}")
    if args.check and changed:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
