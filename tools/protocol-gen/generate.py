def build_registry(enums: dict) -> TypeRegistry:
    underlying = {name: enum.underlying for name, enum in enums.items()}
    flags = {name for name, enum in enums.items() if enum.is_flags}
    return TypeRegistry(underlying, IMPLEMENTED_STRUCTS, set(), flags)


def translate_packet(packet: PacketDef, registry: TypeRegistry) -> tuple[list[str], list[str], str]:
    read_body = packet.read_body or ""
    write_body = packet.write_body or ""
    read_units, _ = iter_units(read_body)
    write_units, _ = iter_units(write_body)
    fields = {f.name: f for f in packet.fields}
    read_translation = translate_read(read_units, Ctx(registry=registry, fields=fields, out="out"))
    write_translation = translate_write(
        write_units, Ctx(registry=registry, fields=fields, out="self")
    )
    # 每个声明的字段都必须真的参与编解码。Crystal 里曾经出现过「字段声明了但读写都漏掉」
    # 的生成缺陷（ManageHeroes 的 Heroes），这里用集合比对把它拦在生成期。
    # 例外：Crystal 自己就既没读也没写的字段（例如 ReportIssue.Message），
    # 读写两侧都不出现时保持一致即可，不算缺陷。
    declared = set(fields)
    translated = set(read_translation.decoded_fields)
    missing = declared - translated
    if missing:
        write_body = packet.write_body or ""
        reused = {name for name in missing if re.search(rf"\b{re.escape(name)}\b", write_body)}
        if reused:
            raise TranslationError(
                f"fields declared but never read (write body does use: {sorted(reused)})"
            )
    if read_translation.signature != write_translation.signature:
        raise TranslationError(
            f"read signature {read_translation.signature} != write signature {write_translation.signature}"
        )
    return read_translation.lines, write_translation.lines, " ".join(read_translation.signature)


def emit_packet_struct(packet: PacketDef, registry: TypeRegistry) -> str:
    read_lines, write_lines, _ = translate_packet(packet, registry)
    lines: list[str] = []
    lines.append(f"/// Crystal `{packet.direction.title()}Packets.{packet.name}` (index {packet.index_value}).")
    lines.append("#[derive(Debug, Clone, Default, PartialEq)]")
    lines.append(f"pub struct {packet.name} {{")
    seen: set[str] = set()
    for decl in packet.fields:
        resolved = registry.resolve(decl.cs_type)
        if resolved is None:
            raise TranslationError(f"unsupported field type {decl.cs_type!r} for {decl.name!r}")
        if resolved.kind == "struct":
            rust_type = f"Option<{resolved.rust}>" if _field_is_optional(packet, decl.name) else resolved.rust
        elif resolved.kind == "array" and _array_is_optional(packet, decl.name):
            element = resolved.rust[len("Vec<") : -1]
            rust_type = f"Vec<Option<{element}>>"
        else:
            rust_type = resolved.rust
        field_name = snake_case(decl.name)
        if field_name in seen:
            field_name += "_"
        seen.add(field_name)
        lines.append(f"    pub {field_name}: {rust_type},")
    lines.append("}")
    lines.append("")
    lines.append(f"impl {packet.name} {{")
    lines.append(f"    /// Packet index used on the wire.")
    lines.append(f"    pub const INDEX: i16 = {packet.index_value};")
    lines.append("    /// Whether Crystal gzip-compresses this packet's payload.")
    lines.append(f"    pub const COMPRESSED: bool = {'true' if packet.compressed else 'false'};")
    lines.append("")
    lines.append("    /// Decode the packet payload (without the header).")
    reader_name = "r" if read_lines else "_r"
    lines.append(
        f"    pub fn decode({reader_name}: &mut crate::PacketReader<'_>) -> Result<Self, crate::ProtocolError> {{"
    )
    if read_lines:
        lines.append("        let mut out = Self::default();")
        for line in read_lines:
            lines.extend(_indent(line, 8))
        lines.append("        Ok(out)")
    else:
        lines.append("        Ok(Self::default())")
    lines.append("    }")
    lines.append("")
    lines.append("    /// Encode the packet payload (without the header).")
    writer_name = "w" if write_lines else "_w"
    lines.append(f"    pub fn encode(&self, {writer_name}: &mut crate::PacketWriter) {{")
    for line in write_lines:
        lines.extend(_indent(line, 8))
    lines.append("    }")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def _indent(line: str, spaces: int) -> list[str]:
    return [(" " * spaces) + line]


def _field_is_optional(packet: PacketDef, field_name: str) -> bool:
    body = (packet.read_body or "").replace("\n", " ")
    body = " ".join(body.split())
    return (
        f"if (reader.ReadBoolean()) {field_name} = " in body
        or f"if (reader.ReadBoolean()) {field_name}=" in body
    )


def _array_is_optional(packet: PacketDef, field_name: str) -> bool:
    """判断数组元素是否「每格一个存在标志」（Crystal 的 `if (…ReadBoolean…) X[i] = …`）。

    覆盖三种写法：`if (reader.ReadBoolean()) X[i] = …`、
    `if (reader.ReadBoolean() == true) X[i] = …`、以及 `if (!reader.ReadBoolean()) continue;`。
    """
    body = (packet.read_body or "").replace("\n", " ")
    body = " ".join(body.split())
    marker = f"{field_name}[i] ="
    if marker not in body:
        return False
    if "reader.ReadBoolean()) continue" in body:
        return True
    # 在 `X[i] =` 之前最近的 80 个字符里出现 ReadBoolean，就说明它是守卫条件。
    position = body.find(marker)
    window = body[max(0, position - 80) : position]
    return "ReadBoolean" in window


def emit_packet_module(packets: list[PacketDef], registry: TypeRegistry, direction: str) -> str:
    chunks = [PACKET_HEADER]
    emitted: list[PacketDef] = []
    failures: list[tuple[str, str]] = []
    for packet in packets:
        if packet.name in HAND_WRITTEN[direction]:
            chunks.append(
                f"pub use crate::manual::{direction}::{packet.name};\n"
            )
            emitted.append(packet)
            continue
        try:
            chunks.append(emit_packet_struct(packet, registry))
            emitted.append(packet)
        except TranslationError as error:
            failures.append((packet.name, str(error)))
    # 本项目**自定义**的包（Crystal 那一版没有）：手写在 manual/ 里，
    # 这里只把它们接进枚举，保证「生成结果 == 提交结果」的自检能通过。
    for extra in EXTRA_PACKETS[direction]:
        chunks.append(f"pub use crate::manual::{direction}::{extra.name};\n")
        emitted.append(extra)
    # 自定义包用到的附属类型也一并再导出，客户端/服务端才能从 `packets::server` 取到。
    for extra_name in EXTRA_REEXPORTS[direction]:
        chunks.append(f"pub use crate::manual::{direction}::{extra_name};\n")
    chunks.append(emit_packet_enum(emitted, direction, registry))
    return "\n".join(chunks), failures


def emit_packet_enum(packets: list[PacketDef], direction: str, registry: TypeRegistry) -> str:
    enum_name = "ClientPacket" if direction == "client" else "ServerPacket"
    lines = [f"/// Every {direction}→{'server' if direction == 'client' else 'client'} packet Crystal understands."]
    lines.append("#[derive(Debug, Clone, PartialEq)]")
    lines.append(f"pub enum {enum_name} {{")
    for packet in packets:
        lines.append(f"    {packet.name}({packet.name}),")
    lines.append("}")
    lines.append("")
    lines.append(f"impl {enum_name} {{")
    lines.append("    /// Packet index used on the wire.")
    lines.append("    #[must_use]")
    lines.append("    pub const fn index(&self) -> i16 {")
    lines.append("        match self {")
    for packet in packets:
        lines.append(f"            Self::{packet.name}(_) => {packet.name}::INDEX,")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    /// Whether this packet's payload is gzip-compressed.")
    lines.append("    #[must_use]")
    lines.append("    pub const fn compressed(&self) -> bool {")
    lines.append("        match self {")
    for packet in packets:
        lines.append(f"            Self::{packet.name}(_) => {packet.name}::COMPRESSED,")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    /// Decode a packet payload (header already stripped) using the id from the header.")
    lines.append("    pub fn decode(index: i16, payload: &[u8]) -> Result<Self, crate::ProtocolError> {")
    lines.append("        match index {")
    for packet in packets:
        lines.append(f"            {packet.name}::INDEX => {{")
        lines.append(
            f"                let body = crate::codec::decompress_if({packet.name}::COMPRESSED, payload)?;"
        )
        lines.append("                let mut r = crate::PacketReader::new(&body);")
        lines.append(f"                Ok(Self::{packet.name}({packet.name}::decode(&mut r)?))")
        lines.append("            }")
    lines.append("            other => Err(crate::ProtocolError::UnknownPacket { index: other }),")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    /// Encode the payload (header excluded).")
    lines.append("    pub fn encode(&self, w: &mut crate::PacketWriter) {")
    lines.append("        match self {")
    for packet in packets:
        lines.append(f"            Self::{packet.name}(p) => p.encode(w),")
    lines.append("        }")
    lines.append("    }")
    lines.append("")
    lines.append("    /// Encode the full frame (header + optional gzip payload).")
    lines.append("    #[must_use]")
    lines.append("    pub fn encode_frame(&self) -> Vec<u8> {")
    lines.append("        let mut w = crate::PacketWriter::new();")
    lines.append("        self.encode(&mut w);")
    lines.append("        crate::codec::frame(self.index(), self.compressed(), w.into_inner())")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    indices_const = "ALL_CLIENT_INDICES" if direction == "client" else "ALL_SERVER_INDICES"
    decode_fn = "decode_client_packet" if direction == "client" else "decode_server_packet"
    indices = ", ".join(f"{packet.name}::INDEX" for packet in packets)
    lines.append(f"/// Every {direction} packet index emitted by this generator.")
    lines.append(f"pub const {indices_const}: &[i16] = &[{indices}];")
    lines.append("")
    lines.append(f"/// Decode a {direction} packet payload by wire index (same dispatch as the enum).")
    lines.append(
        f"pub fn {decode_fn}(index: i16, payload: &[u8]) -> Result<{enum_name}, crate::ProtocolError> {{"
    )
    lines.append(f"    {enum_name}::decode(index, payload)")
    lines.append("}")
    lines.append("")
    lines.extend(emit_roundtrip_test(packets, enum_name))
    lines.extend(emit_boundary_module(packets, direction, enum_name, registry))
    return "\n".join(lines)


def emit_boundary_module(
    packets: list[PacketDef], direction: str, enum_name: str, registry: TypeRegistry
) -> list[str]:
    """Emit field-boundary samples for every encodable field in the packet.

    A sample contains the default bytes of all preceding fields followed by an
    invalid target value.  Fields behind variable/optional/struct payloads are
    listed in `packets_with_uncovered_boundary_fields` instead of being silently
    skipped; packets with no string/list/blob/enum/float field at all go into
    `packets_without_boundary_fields`.
    """
    widths = {
        "bool": 1, "u8": 1, "i8": 1, "u16": 2, "i16": 2,
        "u32": 4, "i32": 4, "u64": 8, "i64": 8, "f32": 4, "f64": 8,
    }
    def default_bytes(op) -> bytes | None:
        if op.kind == "prim":
            width = widths.get(op.rust_type)
            return b"\x00" * width if width else None
        if op.kind == "enum":
            underlying = registry.enum_underlying.get(op.cs_type)
            width = widths.get(underlying or "")
            return b"\x00" * width if width else None
        if op.kind == "string":
            return b"\x00"
        if op.kind in {"list", "blob"}:
            return b"\x00\x00\x00\x00"
        if op.kind == "point":
            return b"\x00" * 8
        return None

    def invalid_bytes(op) -> tuple[bytes, str] | None:
        if op.kind == "string":
            # 7-bit varint for MAX_COLLECTION_LEN + 1 = 1_048_577.
            return bytes([0x81, 0x80, 0x40]), "StringTooLong"
        if op.kind in {"list", "blob"}:
            # count = 0xFFFF, no element bytes -> decoder must error on the first element.
            return bytes([0xFF, 0xFF, 0x00, 0x00]), "CollectionCountHuge"
        if op.kind == "enum":
            return bytes([0xFF]), "EnumUnknown"
        if op.kind == "prim" and op.rust_type == "f32":
            return bytes([0x00, 0x00, 0xC0, 0x7F]), "FloatNotFinite"
        if op.kind == "prim" and op.rust_type == "f64":
            return bytes([0, 0, 0, 0, 0, 0, 0xF8, 0x7F]), "FloatNotFinite"
        return None

    samples: list[tuple[PacketDef, str, bytes, str]] = []
    without: list[PacketDef] = []
    uncovered: list[PacketDef] = []
    for packet in packets:
        has_boundary_field = any(
            op.kind in {"string", "list", "blob", "enum"}
            or (op.kind == "prim" and op.rust_type in {"f32", "f64"})
            for op in packet.ops
        )
        if not has_boundary_field:
            without.append(packet)
            continue
        covered = False
        for target_index, target in enumerate(packet.ops):
            invalid = invalid_bytes(target)
            if invalid is None:
                continue
            prefix = bytearray()
            encodable = True
            for previous in packet.ops[:target_index]:
                default = default_bytes(previous)
                if default is None:
                    encodable = False
                    break
                prefix.extend(default)
            if not encodable:
                continue
            suffix = bytearray()
            for following in packet.ops[target_index + 1 :]:
                default = default_bytes(following)
                if default is None:
                    encodable = False
                    break
                suffix.extend(default)
            if not encodable:
                continue
            payload, kind = invalid
            samples.append(
                (packet, target.field_name, bytes(prefix) + payload + bytes(suffix), kind)
            )
            covered = True
        if not covered:
            uncovered.append(packet)

    lines = ["", "/// Field-boundary sample emitted by the protocol generator."]
    lines.append("#[derive(Debug, Clone, PartialEq, Eq)]")
    lines.append("pub struct BoundarySample {")
    lines.append("    pub index: i16,")
    lines.append("    pub field: &'static str,")
    lines.append("    pub bytes: Vec<u8>,")
    lines.append("}")
    lines.append("")
    lines.append("/// Boundary sample kind for reporting.")
    lines.append("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
    lines.append(
        "pub enum BoundaryKind { StringTooLong, CollectionCountHuge, EnumUnknown, FloatNotFinite }"
    )
    lines.append("")
    lines.append("/// Samples that exercise field boundaries.")
    lines.append("#[must_use]")
    lines.append("pub fn boundary_samples() -> Vec<(BoundarySample, BoundaryKind)> {")
    lines.append("    vec![")
    for packet, field, payload, kind in samples:
        literal = ", ".join(str(byte) for byte in payload)
        lines.append(
            f'        (BoundarySample {{ index: {packet.name}::INDEX, field: "{field}", bytes: vec![{literal}] }}, BoundaryKind::{kind}),'
        )
    lines.append("    ]")
    lines.append("}")
    lines.append("")
    lines.append("/// Four category counts for the receipt.")
    lines.append("#[must_use]")
    lines.append("pub fn boundary_kind_counts() -> (usize, usize, usize, usize) {")
    lines.append("    let samples = boundary_samples();")
    lines.append("    (")
    lines.append("        samples.iter().filter(|(_, k)| *k == BoundaryKind::StringTooLong).count(),")
    lines.append("        samples.iter().filter(|(_, k)| *k == BoundaryKind::CollectionCountHuge).count(),")
    lines.append("        samples.iter().filter(|(_, k)| *k == BoundaryKind::EnumUnknown).count(),")
    lines.append("        samples.iter().filter(|(_, k)| *k == BoundaryKind::FloatNotFinite).count(),")
    lines.append("    )")
    lines.append("}")
    lines.append("")
    lines.append("/// Packets with no string/list/blob/enum/float field at all (pure fixed-width integers).")
    lines.append("#[must_use]")
    lines.append("pub fn packets_without_boundary_fields() -> Vec<i16> {")
    lines.append("    vec![")
    for packet in without:
        lines.append(f"        {packet.name}::INDEX,")
    lines.append("    ]")
    lines.append("}")
    lines.append("")
    lines.append("/// Packets with boundary fields but a preceding non-encodable field; listed, not silently skipped.")
    lines.append("#[must_use]")
    lines.append("pub fn packets_with_uncovered_boundary_fields() -> Vec<i16> {")
    lines.append("    vec![")
    for packet in uncovered:
        lines.append(f"        {packet.name}::INDEX,")
    lines.append("    ]")
    lines.append("}")
    lines.append("")
    lines.append("/// Explicit exemptions: packet + concrete reason; still uncovered, never claimed as tested.")
    lines.append("#[derive(Debug, Clone, Copy, PartialEq, Eq)]")
    lines.append("pub struct BoundaryExemption { pub index: i16, pub reason: &'static str }")
    lines.append("")
    lines.append("#[must_use]")
    lines.append("pub fn boundary_exempt_packets() -> Vec<BoundaryExemption> {")
    lines.append("    vec![")
    for packet in uncovered:
        reason = (
            "nested ClientQuestProgress cannot be Default-encoded; hand-written constructor needed; "
            "its task_list string/count boundaries remain uncovered"
            if packet.name == "ChangeQuest"
            else "preceding field is not encodable by the generator"
        )
        lines.append(
            f'        BoundaryExemption {{ index: {packet.name}::INDEX, reason: "{reason}" }},'
        )
    lines.append("    ]")
    lines.append("}")
    lines.append("")
    return lines


